defmodule GraphlawEx.ProjectionLedgerTest do
  # Every lib/**/*.ex is either a projection (scripts/ggen_sync.sh --list-projections)
  # or a HANDWRITTEN.md ledger row; never both, never neither. No engine needed.
  #
  # async: false: ggen_sync.sh stages ontology/.staged on every invocation, so the
  # projection list is computed once in setup_all and shared, never raced.
  use ExUnit.Case, async: false

  @root Path.expand("..", __DIR__)
  @header "# GENERATED by ggen"

  setup_all do
    {out, status} =
      System.cmd("bash", ["scripts/ggen_sync.sh", "--list-projections"],
        cd: @root,
        stderr_to_stdout: true
      )

    assert status == 0, "ggen_sync.sh --list-projections exited #{status}: #{out}"
    {:ok, projections: String.split(out, "\n", trim: true)}
  end

  defp lib_files do
    @root
    |> Path.join("lib/**/*.ex")
    |> Path.wildcard()
    |> Enum.map(&Path.relative_to(&1, @root))
    |> Enum.sort()
  end

  defp handwritten do
    @root
    |> Path.join("ggen/HANDWRITTEN.md")
    |> File.read!()
    |> String.split("\n")
    |> Enum.flat_map(fn line ->
      case Regex.run(~r/^\|\s*(lib\/\S+\.ex)\s*\|/, line) do
        [_, path] -> [path]
        _ -> []
      end
    end)
  end

  test "no duplicate entries within projections or ledger", %{projections: projections} do
    assert projections -- Enum.uniq(projections) == []
    assert handwritten() -- Enum.uniq(handwritten()) == []
  end

  test "no file is both projected and ledgered as handwritten", %{projections: projections} do
    both = Enum.filter(projections, &(&1 in handwritten()))
    assert both == [], "files in both PROJECTIONS and HANDWRITTEN.md: #{inspect(both)}"
  end

  test "every projected file exists on disk and carries the generated header",
       %{projections: projections} do
    assert projections != []

    missing = Enum.reject(projections, &File.regular?(Path.join(@root, &1)))
    assert missing == [], "projections with no file on disk: #{inspect(missing)}"

    headerless =
      Enum.reject(projections, fn rel ->
        @root
        |> Path.join(rel)
        |> File.stream!()
        |> Enum.take(8)
        |> Enum.any?(&String.starts_with?(&1, @header))
      end)

    assert headerless == [],
           "projected files lacking a `#{@header}` header in the first 8 lines: #{inspect(headerless)}"
  end

  test "every lib file is ledgered exactly once", %{projections: projections} do
    known = projections ++ handwritten()
    unledgered = lib_files() -- known
    assert unledgered == [], "unledgered lib files: #{inspect(unledgered)}"
  end

  test "every ledger entry exists on disk except unrealized projections" do
    ghosts = Enum.reject(handwritten(), &File.exists?(Path.join(@root, &1)))
    assert ghosts == [], "HANDWRITTEN.md rows with no file: #{inspect(ghosts)}"
  end

  test "no lib/ash_graphlaw directory" do
    refute File.dir?(Path.join(@root, "lib/ash_graphlaw"))
  end
end
