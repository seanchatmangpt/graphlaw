#!/usr/bin/env bash
# gen_w3c_manifest.sh — one-time (re-runnable) generator for tests/w3c_manifest.rs
#
# Enumerates the vendored W3C RDF 1.1 test-suite syntax tests under
# tests/fixtures/w3c/{rdf-turtle,rdf-n-triples,rdf-n-quads,rdf-trig,rdf-xml}
# by parsing each dialect's manifest.ttl, and emits a checked-in Rust module
# mapping every (file, kind positive|negative) entry. Only *Syntax tests are
# included — except RDF/XML, where the W3C suite has no TestXMLPositiveSyntax
# class: its positive tests are TestXMLEval entries, admitted here as
# parse-acceptance positives only (graph-isomorphism assertions are out of
# scope for this court). Eval tests elsewhere are skipped with a count in the
# header comment.
#
# Usage: scripts/gen_w3c_manifest.sh   (from repo root)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FIXTURES="$ROOT/tests/fixtures/w3c"
OUT="$ROOT/tests/w3c_manifest.rs"

emit_dialect() {
    local dir="$1" dialect="$2" pos_class="$3" neg_class="$4"
    local manifest="$FIXTURES/$dir/manifest.ttl"
    # blank-line-separated records = manifest entries
    # pos_class: full rdft:Test class counted as Positive
    #   (e.g. TestTurtlePositiveSyntax; for rdf-xml, TestXMLEval — that suite
    #   has no TestXMLPositiveSyntax class, so eval positives are admitted as
    #   parse-acceptance-only)
    # neg_class: full class counted as Negative (e.g. TestTurtleNegativeSyntax)
    awk -v dialect="$dialect" -v pos="$pos_class" -v neg="$neg_class" -v DIR="$(basename "$dir")" '
    BEGIN { RS = "" }
    {
        rec = $0
        kind = ""
        if (rec ~ pos) kind = "Positive"
        else if (rec ~ neg) kind = "Negative"
        else if (rec ~ /rdft:Test/) next   # Eval or other out-of-scope test
        else next                          # not a test entry (prologue/entries list)
        if (match(rec, /mf:action[[:space:]]+<[^>]+>/)) {
            f = substr(rec, RSTART, RLENGTH)
            sub(/.*mf:action[[:space:]]+/, "", f)
            gsub(/[<>]/, "", f)
            printf "    (Dialect::%s, \"%s/%s\", Kind::%s),\n", dialect, DIR, f, kind
        }
    }' "$manifest"
}

# also count skipped eval tests for the header
eval_count() {
    grep -cE 'rdft:Test[A-Za-z]+Eval\b' "$FIXTURES/$1/manifest.ttl" || true
}

TURTLE_EVAL=$(eval_count rdf-turtle)
NT_EVAL=$(eval_count rdf-n-triples)
NQ_EVAL=$(eval_count rdf-n-quads)
TRIG_EVAL=$(eval_count rdf-trig)

{
echo "// GENERATED by scripts/gen_w3c_manifest.sh — do not edit by hand."
echo "// Corpus: W3C RDF 1.1 test suite, vendored under tests/fixtures/w3c/ from"
echo "// https://github.com/w3c/rdf-tests (rdf/rdf11/{rdf-turtle,rdf-n-triples,rdf-n-quads,rdf-trig,rdf-xml})."
echo "// Skipped: Turtle Eval tests ($TURTLE_EVAL), NT eval ($NT_EVAL), NQ eval ($NQ_EVAL),"
echo "// TriG eval ($TRIG_EVAL) — Eval tests assert graph isomorphism, not parse acceptance."
echo "// (RDF/XML Eval tests are NOT skipped: that suite has no PositiveSyntax class,"
echo "// so its eval positives are admitted as parse-acceptance-only positives.)"
echo "// Self-contained enums: every tests/*.rs is its own crate, so this"
echo "// generated module cannot import from w3c_conformance.rs's mod support."
echo "#[allow(dead_code)]"
echo "#[derive(Clone, Copy, PartialEq, Eq, Debug)]"
echo "pub enum Dialect { Turtle, NTriples, NQuads, Trig, RdfXml }"
echo "#[allow(dead_code)]"
echo "#[derive(Clone, Copy, PartialEq, Eq, Debug)]"
echo "pub enum Kind { Positive, Negative }"
echo ""
echo "pub const ENTRIES: &[(Dialect, &str, Kind)] = &["
for spec in "rdf-turtle Turtle TestTurtlePositiveSyntax TestTurtleNegativeSyntax" \
            "rdf-n-triples NTriples TestNTriplesPositiveSyntax TestNTriplesNegativeSyntax" \
            "rdf-n-quads NQuads TestNQuadsPositiveSyntax TestNQuadsNegativeSyntax" \
            "rdf-trig Trig TestTrigPositiveSyntax TestTrigNegativeSyntax" \
            "rdf-xml RdfXml TestXMLEval TestXMLNegativeSyntax"; do
    set -- $spec
    emit_dialect "$1" "$2" "$3" "$4"
done
echo "];"
cat <<'RUST'
#[test]
fn w3c_manifest_census_notice() {
    // LOUD-SKIP census notice: this target is a GENERATED DATA MANIFEST
    // (entries only, no corpus courts of its own). The substantive W3C
    // conformance courts run in tests/w3c_conformance.rs (target
    // `w3c_conformance`). This companion keeps the `w3c_manifest` test target
    // from reporting a silent "0 passed; 0 failed" in a default census.
    println!(
        "SKIP [w3c-manifest] reason: data-only generated manifest ({} entries) consumed via #[path] by tests/w3c_conformance.rs — run the courts there: cargo test --test w3c_conformance",
        ENTRIES.len()
    );
    assert!(!ENTRIES.is_empty(), "generated manifest must be non-empty");
}
RUST
} > "$OUT"

echo "wrote $OUT ($(grep -c 'Dialect::' "$OUT") entries)"
