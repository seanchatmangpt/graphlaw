// build.mjs — assembles the package: copies the pinned wasm artifact and
// repins its BLAKE3 digest into src/generated/artifact-meta.ts.
//
// Phase 1 copies the checked-in, blake3-pinned artifact (priv/graphlaw.wasm).
// Pass GRAPHLAW_WASM_SOURCE=/path/to/graphlaw.wasm to use a fresh build
// (the digest is then taken from the bytes you provide).
//
// Digest strategy: neither node:crypto nor WebCrypto implement BLAKE3, so
// this script computes it with, in order of preference:
//   1. the `b3sum` CLI (external authority; `cargo install b3sum`), or
//   2. the repo's own pure-TypeScript implementation (src/blake3.ts),
//      transpiled in-memory with the devDependency `typescript`.
// Both paths must agree byte-for-byte (test/blake3.test.ts proves the TS
// implementation against b3sum directly).
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '..', '..');

const defaultSource = join(repoRoot, 'priv', 'graphlaw.wasm');
const source = process.env.GRAPHLAW_WASM_SOURCE ?? defaultSource;
const bytes = readFileSync(source);

/** b3sum over a file path; null when the binary is unavailable. */
function digestViaB3sum(path) {
  try {
    const out = execFileSync('b3sum', [path], { encoding: 'utf8' });
    return out.trim().split(/\s+/)[0] || null;
  } catch {
    return null;
  }
}

/** BLAKE3 via src/blake3.ts transpiled with the typescript devDependency. */
async function digestViaLocalTs(data) {
  const { transpileModule } = await import('typescript');
  const tsSource = readFileSync(join(pkgRoot, 'src', 'blake3.ts'), 'utf8');
  const js = transpileModule(tsSource, {
    compilerOptions: {
      module: 99 /* ESNext */,
      target: 4 /* ES2022 */,
    },
  }).outputText;
  const mod = await import(
    'data:text/javascript;base64,' + Buffer.from(js, 'utf8').toString('base64')
  );
  return mod.blake3Hex(new Uint8Array(data));
}

async function blake3Of(path, data) {
  const viaB3 = digestViaB3sum(path);
  const viaTs = await digestViaLocalTs(data);
  if (viaB3 !== null && viaB3 !== viaTs) {
    console.error(`build: b3sum and src/blake3.ts disagree!\n  b3sum: ${viaB3}\n  ts:    ${viaTs}`);
    process.exit(1);
  }
  return viaB3 ?? viaTs;
}

const sha = await blake3Of(source, bytes);

const pinnedPath = join(repoRoot, 'priv', 'graphlaw.wasm.blake3');
const pinned = readFileSync(pinnedPath, 'utf8').trim().split(/\s+/)[0];
if (source === join(repoRoot, 'priv', 'graphlaw.wasm') && sha !== pinned) {
  console.error(`build: checked-in artifact digest drift!\n  on disk: ${sha}\n  pinned:  ${pinned}`);
  process.exit(1);
}

mkdirSync(join(pkgRoot, 'wasm'), { recursive: true });
copyFileSync(source, join(pkgRoot, 'wasm', 'graphlaw.wasm'));

// Assemble dist-nodejs/ from the tsc output (tsc -p tsconfig.build.json runs
// after this script in `npm run build`; it emits to tsc-out with rootDir src).
// Phase 2 adds dist-web/ and dist-bundler/ assemblies.


// The generated header must be path-independent: CI rebuilds the artifact at
// a different absolute path than a dev checkout, and the js-drift job runs
// `git diff --exit-code` on this file. Always emit the repo-relative label.
const provenanceLabel =
  source === defaultSource ? 'priv/graphlaw.wasm' : String(source);
const meta = `// GENERATED by scripts/build.mjs from ${provenanceLabel}.
// Do not edit by hand; the digest is re-pinned on every build.
export const WASM_BLAKE3 = '${sha}';
`;
mkdirSync(join(pkgRoot, 'src', 'generated'), { recursive: true });
writeFileSync(join(pkgRoot, 'src', 'generated', 'artifact-meta.ts'), meta);
console.log(`build: wasm/graphlaw.wasm in place (blake3 ${sha})`);
